def _sprite(name: str, raw: str) -> tuple[str, ...]:
    rows = [r for r in raw.strip("\n").splitlines()]
    if len(rows) != SIZE or any(len(r) != SIZE for r in rows):
        bad = [(i, len(r)) for i, r in enumerate(rows) if len(r) != SIZE]
        raise ValueError(f"sprite {name!r} is not {SIZE}x{SIZE}: {bad}")
    return tuple(rows)


SPRITES = {name: _sprite(name, raw) for name, raw in RAW.items()}


# --------------------------------------------------------------------------- registry
def registry() -> dict[str, list[str]]:
    """category class -> item ids, parsed from the registry stubs."""
    out: dict[str, list[str]] = {}
    for path in sorted(ITEMS_SRC.glob("*.java")):
        src = path.read_text()
        ids = re.findall(r'ModItems\.add(?:Item)?\("([a-z_]+)"', src)
        if ids:
            out[path.stem] = ids
    return out


def known_ids() -> list[str]:
    return [item for ids in registry().values() for item in ids]



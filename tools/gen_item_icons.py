def pal_for(name: str, shape: str) -> dict[str, tuple[int, int, int]]:
    pal = dict(PALETTES[name])
    # One-off glows that should not change with the material.
    if shape in {"candle", "incense"}:
        pal["e"] = (255, 178, 62)
    elif shape == "compass":
        pal["e"] = (216, 64, 52)
    elif shape == "eye":
        pal["e"] = (226, 196, 92)
    elif shape == "bomb":
        pal["e"] = (255, 196, 72)
    elif shape == "lantern":
        pal["g"] = (226, 196, 118)
    return pal



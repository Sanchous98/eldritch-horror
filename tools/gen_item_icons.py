"""Procedural 16x16 item-icon set for Eldritch Horror.

The icons are drawn from tiny ASCII sprites (one per silhouette family), recoloured by a
material palette chosen from the item id, then finished with a 1px dark outline and a few
deterministic "wear" pixels so near-identical items never share the exact same image.

Everything is seeded per item id, so the pass is deterministic and rerunnable:

    python3 tools/gen_item_icons.py            # write all registered item icons
    python3 tools/gen_item_icons.py --sheet    # ...and build/icon-sheet2.png for review

It also runs automatically from tools/gen_assets.py.

Sprite roles (resolved by the palette):
    .  transparent        b  body/base        l  light face        d  shadow face
    a  accent (grip, ink, trim)               A  accent highlight
    w  metal/glass shine  g  glass/water fill  e  glow (flame, eye, needle)
"""

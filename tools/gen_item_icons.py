def _mix(a, b, t):
    return tuple(int(round(x + (y - x) * t)) for x, y in zip(a, b))


def _mul(c, f):
    return tuple(max(0, min(255, int(round(v * f)))) for v in c)


def _pal(base, light, dark, accent, glow=None):
    return {
        "b": base,
        "l": light,
        "d": dark,
        "a": accent,
        "A": _mix(accent, (255, 255, 255), 0.32),
        "w": _mix(light, (255, 255, 255), 0.55),
        "g": _mix(base, light, 0.62),
        "e": glow or _mix(accent, (255, 255, 255), 0.45),
    }



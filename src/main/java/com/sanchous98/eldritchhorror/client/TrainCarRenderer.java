package com.sanchous98.eldritchhorror.client;

import com.mojang.blaze3d.vertex.PoseStack;
import com.mojang.math.Axis;
import com.sanchous98.eldritchhorror.client.model.TrainCarModel;
import com.sanchous98.eldritchhorror.entity.TrainCar;
import net.minecraft.client.model.Model;
import net.minecraft.client.renderer.SubmitNodeCollector;
import net.minecraft.client.renderer.entity.EntityRenderer;
import net.minecraft.client.renderer.entity.EntityRendererProvider;
import net.minecraft.client.renderer.state.level.CameraRenderState;
import net.minecraft.client.renderer.texture.OverlayTexture;
import net.minecraft.resources.Identifier;
import net.minecraft.world.phys.AABB;

/**
 * Draws the full-size carriage and locomotive models ({@link TrainCarModel}).
 *
 * <p>One renderer serves both entity types; registration supplies the baked model and atlas. The
 * model is authored in blocks already, so there is no art scale here — the outer pose only turns
 * the car to its trail heading ({@code 180 - yaw}, the vanilla minecart convention for a model
 * whose nose points at −Z). The culling box is widened to the car length by
 * {@link TrainCar#renderBounds}; the entity box in {@code ModEntities} is only the cross-section.
 *
 * <p>Client-only, registered from {@link ClientEntityRenderers} (a {@code Dist.CLIENT}
 * subscriber); the dedicated server never loads this class.
 *
 * @param <T> locomotive or wagon
 */
public final class TrainCarRenderer<T extends TrainCar>
        extends EntityRenderer<T, TrainRenderState> {

    private final Model<TrainRenderState> model;
    private final Identifier texture;

    /**
     * @param context      renderer context
     * @param model        baked wagon or locomotive model
     * @param texture      256×256 atlas generated by {@code tools/generate_train_textures.py}
     * @param shadowRadius how wide the ground shadow is, in blocks
     */
    public TrainCarRenderer(EntityRendererProvider.Context context,
                            Model<TrainRenderState> model, Identifier texture,
                            float shadowRadius) {
        super(context);
        this.model = model;
        this.texture = texture;
        this.shadowRadius = shadowRadius;
    }

    @Override
    public TrainRenderState createRenderState() {
        return new TrainRenderState();
    }

    @Override
    public void extractRenderState(T car, TrainRenderState state, float partialTicks) {
        super.extractRenderState(car, state, partialTicks);
        state.yRot = car.getYRot(partialTicks);
    }

    @Override
    public void submit(TrainRenderState state, PoseStack poseStack,
                       SubmitNodeCollector submitNodeCollector, CameraRenderState camera) {
        super.submit(state, poseStack, submitNodeCollector, camera);
        poseStack.pushPose();
        poseStack.rotateDegrees(Axis.YP, 180.0F - state.yRot);
        submitNodeCollector.submitModel(this.model, state, poseStack, this.texture,
                state.lightCoords, OverlayTexture.NO_OVERLAY, state.outlineColor);
        poseStack.popPose();
    }

    @Override
    protected AABB getBoundingBoxForCulling(T car, float partialTicks) {
        return car.renderBounds(partialTicks);
    }
}
